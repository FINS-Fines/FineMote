#ifndef FINEMOTE_BMS_POWER_ENABLE_HPP
#define FINEMOTE_BMS_POWER_ENABLE_HPP

#include "BMS_Types.hpp"

struct BMS_PowerEnable
{
    int8_t level = -1;
    const char* levelText = "\xE6\x9C\xAA\xE7\x9F\xA5";
    const char* stateText = "\xE7\x8A\xB6\xE6\x80\x81\xE6\x9C\xAA\xE7\x9F\xA5\xEF\xBC\x88PCF8574 \xE6\x9C\xAA\xE8\xBF\x9E\xE6\x8E\xA5\xE6\x88\x96\xE9\x87\x87\xE6\xA0\xB7\xE6\x97\xA0\xE6\x95\x88\xEF\xBC\x89";
};

inline BMS_PowerEnable BMS_DecodePowerEnable(const BMS_Sample& sample)
{
    if ((sample.validMask & BMS_SourcePcf8574) == 0U) return {};
    if ((sample.pcf8574 & 0x80U) != 0U) {
        return {1, "\xE9\xAB\x98\xE7\x94\xB5\xE5\xB9\xB3", "\xE8\xBF\x9E\xE6\x8E\xA5\xE7\x94\xB5\xE6\xBA\x90"};
    }
    return {0, "\xE4\xBD\x8E\xE7\x94\xB5\xE5\xB9\xB3", "\xE6\x96\xAD\xE5\xBC\x80\xE7\x94\xB5\xE6\xBA\x90\xEF\xBC\x8C\xE6\x80\xA5\xE5\x81\x9C\xE6\x8C\x89\xE4\xB8\x8B"};
}

#endif
